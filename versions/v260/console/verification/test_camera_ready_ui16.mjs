import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const source=await fs.readFile(new URL('../static/camera.js',import.meta.url),'utf8');
const timers=new Map();let timerId=0;
const context={setTimeout(fn,ms){const id=++timerId;timers.set(id,{fn,ms});return id},clearTimeout(id){timers.delete(id)},clearInterval(){},setInterval(){return 99},location:{protocol:'http:'},WebSocket:{OPEN:1}};
vm.runInNewContext(source.replace('export class Camera','class Camera')+';globalThis.Camera=Camera',context);
let statuses=[],sent=[];const video={srcObject:null};
const camera=new context.Camera(video,(...state)=>statuses.push(state),()=>{});
camera.ws={readyState:1,send(value){sent.push(JSON.parse(value))},close(){}};
await camera.message({type:'list',producers:[]});
assert.equal(statuses.at(-1)[0],'connecting','empty startup list should wait, not fail');
let retry=timers.get(camera.producerTimer);assert.equal(retry.ms,250);retry.fn();
assert.deepEqual(sent,[{type:'list'}]);
await camera.message({type:'list',producers:[{id:'real-camera'}]});
assert.equal(timers.has(camera.producerTimer),false);
assert.deepEqual(sent.at(-1),{type:'startSession',peerId:'real-camera'});
camera.sessionRequested=false;
await camera.message({type:'list',producers:[]});
const pending=timers.get(camera.producerTimer);const count=sent.length;
camera.disconnect();assert.equal(timers.has(camera.producerTimer),false);
pending.fn();assert.equal(sent.length,count,'a delayed list callback cannot reconnect after disconnect');
console.log(JSON.stringify({passed:true,scope:'startup empty producer list waits on one socket; ready producer starts one session; disconnect cancels pending startup callbacks'}));
