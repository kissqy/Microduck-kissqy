import assert from 'node:assert/strict';
import * as T from '../docs/vendor/three.module.min.js?demo=20261013';
import {softenCableCorners} from '../docs/assembly-wire-curves.js';
const a=new T.Vector3(-.03,-.01,0),corner=new T.Vector3(),b=new T.Vector3(.01,.03,0);
const points=[a,new T.Vector3(-.02,0,0),corner,new T.Vector3(0,.02,0),b];
const sharp=new T.CurvePath();for(let i=1;i<points.length;i++)sharp.add(new T.LineCurve3(points[i-1],points[i]));
const rounded=softenCableCorners(sharp);
assert(rounded.getPoint(0).distanceTo(a)<1e-12);assert(rounded.getPoint(1).distanceTo(b)<1e-12);
assert.equal(rounded.curves.filter(c=>c.isQuadraticBezierCurve3).length,3);
for(let i=1;i<rounded.curves.length;i++)assert(rounded.curves[i-1].getTangent(1).dot(rounded.curves[i].getTangent(0))>.999999,'bend must join its straight leads tangentially');
const forbidden=new T.Vector3(-.000875,.000875,0);
const accept=curve=>curve.getPoints(80).every(p=>p.distanceTo(forbidden)>.00045);
const constrained=softenCableCorners(sharp,{accept});
assert(accept(constrained),'fillet cut through a nearby obstruction');
const middle=curve=>curve.curves.find(c=>c.isQuadraticBezierCurve3&&c.v1.distanceTo(corner)<1e-12);
const bend=middle(constrained);assert(bend,'clear smaller bend was lost');
assert(bend.v0.distanceTo(corner)<middle(rounded).v0.distanceTo(corner),'bend did not adapt to available clearance');
assert.equal(softenCableCorners(rounded),rounded,'existing smooth segments must remain intact');
console.log('PASS: visible tangent fillets, fixed contacts and clearance-adaptive bend radius.');
